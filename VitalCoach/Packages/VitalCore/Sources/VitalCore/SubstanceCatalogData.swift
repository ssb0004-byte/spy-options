import Foundation

/// The bundled, verified substance catalog.
///
/// **Maintenance rules** (see docs/SMART_ROUTINE_ENTRY.md):
/// - Every name must exist in a public reference: RxNorm / DailyMed / Drugs@FDA for medicines,
///   NIH Office of Dietary Supplements fact sheets for vitamins, minerals and supplements, and the
///   peer-reviewed literature (PubMed) or FDA's bulk-drug-substance lists for peptides and
///   compounded ingredients.
/// - Changes go through a pull request; bump `version` with every change.
/// - Notes state regulatory facts only. They are not recommendations.
/// - User-created names are stored separately on the device and never added here.
public enum SubstanceCatalog {
    public static let version = "2026.10.1"

    public static let sources = [
        "RxNorm (U.S. National Library of Medicine)",
        "DailyMed / Drugs@FDA (U.S. FDA)",
        "NIH Office of Dietary Supplements fact sheets",
        "PubMed (peer-reviewed literature)",
        "FDA 503A bulk drug substances categories",
    ]

    public static func entries(in category: SubstanceCategory) -> [CatalogEntry] {
        entries.filter { $0.categories.contains(category) }
    }

    public static let entries: [CatalogEntry] = prescription + otc + vitaminsMinerals + sportsSupplements + peptides + hormones + compounded
}

private func e(_ id: String, _ name: String, _ cats: [SubstanceCategory], _ aliases: [String] = [],
               routes: [AdministrationRoute] = [.oral], unit: DoseUnit? = .milligram, pop: Int = 50,
               note: String? = nil) -> CatalogEntry {
    CatalogEntry(id: id, name: name, categories: cats, aliases: aliases, routes: routes, unitHint: unit, popularity: pop, note: note)
}

